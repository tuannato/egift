/**
 * Core cylinder: an armoured cylinder of four tiers lying back in a tilted
 * launch cradle, seen from an oblique angle a little above, drawn like a
 * painted animation cel: flat fills, one hard shadow shape per form, white
 * highlight slashes, ink lines. Off-white armour, one strong blue, hazard
 * yellow, a cold core.
 *
 * Opening, in five beats:
 *   1. the status lamps on the collar come on, one after another;
 *   2. the two cradle clamps let go of tiers two and three and draw back;
 *   3. the handle ring on the cap turns a quarter turn (edge-on, then
 *      face-on) and the cap lifts along the axis;
 *   4. the tiers part along the axis: the top one a little, the foot down
 *      into its collar, then the upper half slides far up the spine rail,
 *      each with a small overshoot and a shake; four vent flaps swing out;
 *   5. between the halves stands the core, and its light grows.
 *
 * Canvas 360x450. The art is generated by scripts/art/cylinder.gen.mjs, which
 * draws the cylinder upright and leans it as a whole; the boxes below are the
 * ones it prints.
 */

/** How far the axis leans from upright (clockwise), as in the generator. */
const LEAN = 24;
const SI = Math.sin((LEAN * Math.PI) / 180);
const CO = Math.cos((LEAN * Math.PI) / 180);
const r2 = (n: number) => Math.round(n * 100) / 100;
/** A slide of `d` units up the axis (negative: down it). */
const up = (d: number) => ({ x: r2(d * SI), y: r2(-d * CO) });
/** A slide of `d` units across the axis, to the right (negative: to the left). */
const across = (d: number) => ({ x: r2(d * CO), y: r2(d * SI) });

/** One parallax depth for the cylinder and everything that touches it, so that nothing tears apart. */
const D = 0.3;

/** How far each part travels along the axis. */
const GAP_1 = 10;
const FOOT = -8;
const BIG = 76;
const CAP_UNSEAT = 12;
const CLAMP_BACK = 30;
const FLAP_TURN = 44;

