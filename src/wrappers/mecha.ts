import type { IdleStep, LayerDef, Step, WrapperDef } from '../stage/format';
import { scaled, together, tune } from './tune';

/**
 * Mecha capsule: an armoured blast-door cask held in a docking ring inside a
 * dark hangar, front-on. Light drawn on graphite: cool white edges, a few
 * white armour plates, and one orange standby light in the central lock.
 *
 * Opening, four mechanical beats:
 *   1. the lock light turns from orange to white, the lock turns one step,
 *      and the ring's four clamps let go of the seam ends;
 *   2. the four leaves unseat and slide out diagonally into the ring;
 *   3. the eight-blade iris behind them opens as a growing octagon;
 *   4. the core, an ingot of cyan-white light, is exposed and its light falls
 *      on the inner edges of the leaves and on the floor.
 *
 * Canvas 360x450, lock centre at (180, 200). Art is generated by
 * scripts/art/mecha.gen.mjs in canvas units (each SVG's viewBox is its box).
 */

const C = [180, 200] as const;
/** How far each leaf travels on each axis (matches D in the generator: the spill light is drawn for it). */
const LEAF_D = 28;
/** How far each iris blade travels along its own spoke to clear the hole. */
const BLADE_S = 41;
/** One parallax depth for the whole cask and the clamps that grip it, so it never tears apart. */
const D_CASK = 0.42;

const FBOX = [74, 40, 212, 320] as const;
const IBOX = [C[0] - 60, C[1] - 60, 120, 120] as const;

const LEAVES: readonly (readonly [string, number, number])[] = [
    ['leaf-tl', -1, -1],
    ['leaf-br', 1, 1],
    ['leaf-tr', 1, -1],
    ['leaf-bl', -1, 1],
];
const BLADES = [0, 1, 2, 3, 4, 5, 6, 7] as const;

const layers: LayerDef[] = [
    { id: 'hangar', art: 'hangar.svg', box: [-8, -8, 376, 466], depth: 0.06 },
    { id: 'ring', art: 'ring.svg', box: [0, 0, 360, 410], depth: 0.2 },
    { id: 'cavity', art: 'cavity.svg', box: [C[0] - 56, C[1] - 56, 112, 112], depth: D_CASK },
    { id: 'core', art: 'core.svg', box: [C[0] - 44, C[1] - 44, 88, 88], blend: 'screen', depth: D_CASK, start: { opacity: 0, sx: 0.7, sy: 0.7 } },
    ...BLADES.map((k): LayerDef => ({ id: `blade-${k}`, art: `blade-${k}.svg`, box: IBOX, depth: D_CASK })),
    { id: 'lock-white', art: 'lock-white.svg', box: IBOX, blend: 'screen', depth: D_CASK, start: { opacity: 0 } },
    { id: 'front', art: 'front.svg', box: FBOX, depth: D_CASK },
    ...LEAVES.map(([id]): LayerDef => ({ id, art: `${id}.svg`, box: FBOX, depth: D_CASK })),
    { id: 'lock-orange', art: 'lock-orange.svg', box: [120, 140, 120, 310], blend: 'screen', depth: D_CASK, start: { opacity: 0.85 } },
    { id: 'clamps-we', art: 'clamps-we.svg', box: [0, 0, 360, 400], depth: D_CASK },
    { id: 'clamps-ns', art: 'clamps-ns.svg', box: [0, 0, 360, 400], depth: D_CASK },
    { id: 'spill', art: 'spill.svg', box: [0, 0, 360, 450], blend: 'screen', depth: D_CASK, start: { opacity: 0 } },
    { id: 'fore', art: 'fore.svg', box: [-20, -20, 400, 490], depth: 0.9 },
    { id: 'dust', art: 'dust.svg', box: [C[0] - 4, C[1] - 4, 8, 8], blend: 'screen', depth: 0 },
];

// Beat times (ms).
const UNLOCK = 300;
const SLIDE = 1150;
const IRIS = 2250;
const CORE = 2550;

const spoke = (k: number): [number, number] => {
    // After the lock's one-step turn, blade k sits on the spoke of blade k + 1.
    const a = Math.PI / 8 + ((k + 1) * Math.PI) / 4;
    return [Math.round(Math.cos(a) * BLADE_S * 100) / 100, Math.round(Math.sin(a) * BLADE_S * 100) / 100];
};

const open: Step[] = [
    // 1. Standby orange gives way to white; the lock turns one step and seats; the clamps let go.
    { kind: 'move', layer: 'lock-orange', at: 0, dur: 320, ease: 'inout', to: { opacity: 0 } },
    { kind: 'move', layer: 'lock-white', at: 60, dur: 320, ease: 'out', to: { opacity: 1 } },
    ...BLADES.map((k): Step => ({ kind: 'move', layer: `blade-${k}`, at: UNLOCK, dur: 520, ease: 'back', to: { turn: 45 } })),
    { kind: 'move', layer: 'lock-white', at: UNLOCK, dur: 520, ease: 'back', to: { turn: 45 } },
    { kind: 'move', layer: 'clamps-we', at: 380, dur: 420, ease: 'back', to: { sx: 1.13 } },
    { kind: 'move', layer: 'clamps-ns', at: 620, dur: 420, ease: 'back', to: { sy: 1.09 } },

    // 2. The leaves unseat with a jolt, then slide out along the diagonals: the big pair first.
    ...LEAVES.flatMap(([id, dx, dy], i): Step[] => {
        const lag = i < 2 ? 0 : 130;
        return [
            { kind: 'move', layer: id, at: SLIDE - 190 + lag, dur: 110, ease: 'out', to: { x: dx * 2.5, y: dy * 2.5 } },
            { kind: 'move', layer: id, at: SLIDE + lag, dur: 820, ease: 'inout', to: { x: dx * LEAF_D, y: dy * LEAF_D } },
            { kind: 'shake', layer: id, at: SLIDE + lag + 820, dur: 200, amp: 1.2, times: 2 },
        ];
    }),

    // 3. The iris opens: every blade slides out along its spoke, the hole growing as an octagon.
    { kind: 'move', layer: 'lock-white', at: IRIS - 60, dur: 220, ease: 'out', to: { opacity: 0 } },
    ...BLADES.map((k): Step => {
        const [x, y] = spoke(k);
        return { kind: 'move', layer: `blade-${k}`, at: IRIS, dur: 700, ease: 'inout', to: { x, y } };
    }),

    // 4. The core is exposed; its light reaches the leaves and the floor, peaks, and settles.
    { kind: 'move', layer: 'core', at: CORE, dur: 550, ease: 'out', to: { opacity: 1, sx: 1.06, sy: 1.06 } },
    { kind: 'move', layer: 'core', at: CORE + 650, dur: 900, ease: 'inout', to: { sx: 1, sy: 1 } },
    { kind: 'move', layer: 'spill', at: CORE + 60, dur: 420, ease: 'out', to: { opacity: 1 } },
    { kind: 'move', layer: 'spill', at: CORE + 600, dur: 1000, ease: 'inout', to: { opacity: 0.72 } },
    { kind: 'move', layer: 'hangar', at: SLIDE, dur: 2600, ease: 'out', to: { sx: 1.02, sy: 1.02 } },
    { kind: 'move', layer: 'fore', at: SLIDE, dur: 2600, ease: 'out', to: { sx: 1.06, sy: 1.06 } },
    // Dust shaken loose drifts out and down.
    { kind: 'scatter', layer: 'dust', at: CORE + 120, dur: 1500, count: 26, spread: 150, fall: 34 },
    { kind: 'scatter', layer: 'dust', at: CORE + 320, dur: 1250, count: 14, spread: 90, fall: 20 },
];

const idle: IdleStep[] = [
    { layer: 'lock-orange', field: 'opacity', amp: 0.15, period: 4400 },
    { layer: 'fore', field: 'x', amp: 2.5, period: 13000 },
    { layer: 'hangar', field: 'y', amp: 0.8, period: 17000, phase: 0.3 },
];

const afterglow: IdleStep[] = [
    { layer: 'core', field: 'sx', amp: 0.025, period: 3800 },
    { layer: 'core', field: 'sy', amp: 0.025, period: 3800 },
    { layer: 'spill', field: 'opacity', amp: 0.1, period: 3800 },
    { layer: 'fore', field: 'x', amp: 2.5, period: 13000 },
];

export const mecha: WrapperDef = {
    id: 'mecha',
    name: { vi: 'Hộp cơ giáp', en: 'Mecha capsule' },
    ambient: ['#1C2430', '#E8470A', '#BFF3FF'],
    blurb: {
        vi: 'Khoang giáp tám cạnh neo trong vòng đỡ, khoá sáng cam. Kẹp nhả, bốn tấm giáp trượt chéo, mống mắt mở và lõi sáng xanh trắng lộ ra.',
        en: 'An armoured cask in a docking ring, its lock lit orange. Clamps release, four plates slide apart, the iris opens on a core of cold light.',
    },
    // White armour plate, cut corners, hazard orange: the frame becomes a panel of the machine.
    theme: { ground: '#0A0C0F', surface: '#E9EBEE', ink: '#11151A', accent: '#E8470A', onAccent: '#0B0E12', material: 'plate', corner: 'cut', face: 'tech', voice: 'servo' },
    focus: [0.5, C[1] / 450],
    size: [360, 450],
    backdrop: '#0A0C0F',
    layers,
    idle,
    afterglow,
    open,
    revealAt: 3050,
    // A machine waking: fifths climbing on a muted horn, over a ticking of wood.
    sound: {
        v: 1,
        inst: 'brass',
        tonic: 62,
        score: scaled(1.3, together(
            tune(150, 'D4/4 A4/4 D5/4 A4/4 | D5/4 F#5/4 A5/2!'),
            tune(150, 'D3/8 D3/8 D3/8 D3/8 D3/8 D3/8 D3/8 D3/8 | D3/8 D3/8 D3/8 D3/8 D3/2', { inst: 'wood', gain: 0.4 }),
        )),
    },
};

export default mecha;
